"""The scripting reference generated from the step registry (plans/architecture.md ARC-12 item 4): one Markdown page
per area in docs/api/, each step with its help, inputs, outputs and parameters with their defaults. The same text
as `astrowb-cli help <step>`, so the page and the command never disagree.

    python tools/api_docs.py [docs/api]          # writes the pages; --check fails when they are out of date
"""

import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))


def pages():
    """{file name: Markdown} for every area of the registry, and the index."""
    from astrowb.cli import describe
    from astrowb.engine import steps

    steps._load_builtin()
    areas = {}
    for sid in sorted(steps.REGISTRY):
        areas.setdefault(sid.split(".")[0], []).append(sid)
    out = {}
    for area, ids in areas.items():
        parts = [f"# {area}\n\nPython: `from astrowb import api; api.{area}.<step>(…)`; command line: "
                 f"`astrowb-cli run {area}.<step> key=value …`.\n"]  # fmt: skip
        for sid in ids:
            text = io.StringIO()
            describe(sid, text)
            parts.append(f"## {sid}\n\n```text\n{text.getvalue().rstrip()}\n```\n")
        out[f"{area}.md"] = "\n".join(parts)
    index = ["# Scripting reference\n", "Generated by tools/api_docs.py from the step registry: do not edit.\n"]
    index += [f"- [{area}]({area}.md): {len(ids)} steps" for area, ids in areas.items()]
    out["README.md"] = "\n".join(index) + "\n"
    out["recipe.schema.json"] = recipe_schema(steps)
    return out


TYPES = {"int": "integer", "float": "number", "bool": "boolean", "text": "string", "choice": None, "band": "string",
         "file": "string", "folder": "string", "time": "number", "expression": "string"}  # fmt: skip


def recipe_schema(steps):
    """JSON Schema of an automation / recipe file (AUT-1 item 5): an editor then checks the step names and each
    step's settings — kind, range, choices — while the file is written."""
    import json

    rules = []
    for sid, s in sorted(steps.REGISTRY.items()):
        props = {}
        for p in s.params:
            prop = {"description": p.label + (f" ({p.unit})" if p.unit else "") + (": " + p.help if p.help else "")}
            kind = TYPES.get(p.kind)
            if kind:
                prop["type"] = [kind, "null"]
            if p.choices:
                prop["enum"] = [*p.choices, None]
            if p.min is not None:
                prop["minimum"] = p.min
            if p.max is not None:
                prop["maximum"] = p.max
            props[p.name] = prop
        params = {"type": "object", "properties": props, "additionalProperties": not s.params}
        rules.append({"if": {"properties": {"step": {"const": sid}}}, "then": {"properties": {"params": params}}})
    step = {"type": "object", "required": ["step"], "allOf": rules,
            "properties": {"step": {"enum": sorted(steps.REGISTRY)}, "inputs": {"type": "object"},
                           "params": {"type": "object"}, "each": {"type": "string"}}}  # fmt: skip
    schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "Automation (recipe)",
              "type": "object", "required": ["steps"],
              "properties": {"name": {}, "description": {}, "inputs": {"type": "object"},
                             "sequence": {"type": "object"}, "steps": {"type": "array", "items": step}}}  # fmt: skip
    return json.dumps(schema, indent=1, ensure_ascii=False) + "\n"


def write(folder):
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    for name, text in pages().items():
        (folder / name).write_text(text, encoding="utf-8")
    return folder


def stale(folder):
    """Names of the pages that differ from what the registry gives now (missing ones included)."""
    folder = Path(folder)
    return [n for n, t in pages().items() if not (folder / n).exists() or (folder / n).read_text("utf-8") != t]


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    target = args[0] if args else "docs/api"
    if "--check" in sys.argv:
        old = stale(target)
        print("\n".join(old) if old else "up to date")
        sys.exit(1 if old else 0)
    print(write(target))
