"""The validation report (plans/validation.md VAL-3): every row the validation tests wrote to validation-results/,
beside the plan's tolerance table, so a quantity without a test shows as "not yet tested".

    pytest tests/validation && python tools/validation_report.py [validation-results] [docs/validation/report.md]
    python tools/validation_report.py --save <version> [validation-results]     # docs/validation/history/
    python tools/validation_report.py --diff <old.json> <new.json>              # the science changes (VAL-5)
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def planned():
    """(area, quantity, compared with, tolerance, step) rows of the table in plans/validation.md VAL-3."""
    text = (ROOT / "plans" / "validation.md").read_text(encoding="utf-8")
    block = text.split("### VAL-3.", 1)[1].split("### VAL-4.", 1)[0]
    rows = []
    for line in block.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 5 and cells[0] not in ("Area", "---") and not re.fullmatch(r"-+", cells[0]):
            rows.append(cells)
    return rows


def rows_of(results):
    measured = []
    for f in sorted(Path(results).glob("*.json")):
        measured += json.loads(f.read_text(encoding="utf-8"))["rows"]
    return measured


def _number(text):
    m = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", str(text))
    return float(m.group()) if m else None


def diff(old, new):
    """Rows whose measured number moved by more than a third of its tolerance: [(area, quantity, old, new,
    tolerance)]; rows only in one run are listed with None on the other side."""

    def key(r):
        return r["area"], r["quantity"]

    a, b = {key(r): r for r in old}, {key(r): r for r in new}
    out = []
    for k in sorted(set(a) | set(b)):
        ra, rb = a.get(k), b.get(k)
        if ra is None or rb is None:
            out.append((*k, ra and ra["measured"], rb and rb["measured"], (ra or rb)["tolerance"]))
            continue
        va, vb, tol = _number(ra["measured"]), _number(rb["measured"]), _number(rb["tolerance"])
        if None in (va, vb, tol) or abs(vb - va) > tol / 3:
            out.append((*k, ra["measured"], rb["measured"], rb["tolerance"]))
    return out


def build(results):
    measured = rows_of(results)
    out = ["# Validation report", "", "Generated by tools/validation_report.py from a validation run; do not edit.", ""]
    for area in dict.fromkeys(r[0] for r in planned()):
        out += [f"## {area}", "", "| Quantity | Compared with | Tolerance | Measured | Verdict | Test | Data |",
                "| --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
        mine = [m for m in measured if m["area"] == area]
        for m in mine:
            out.append(f"| {m['quantity']} | {m['compared_with']} | {m['tolerance']} | {m['measured']} | "
                       f"{m['verdict']} | `{m['test']}` | {m['data']} |")  # fmt: skip
        tested = {m["step"] for m in mine}
        for _a, quantity, compared, tolerance, step in (r for r in planned() if r[0] == area):
            if not any(t and t in step for t in tested):  # a test names its step ("PHO-26") as the plan does
                out.append(f"| {quantity} | {compared} | {tolerance} | — | not yet tested | {step} | |")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    if sys.argv[1:2] == ["--diff"]:
        old, new = (json.loads(Path(p).read_text(encoding="utf-8"))["rows"] for p in sys.argv[2:4])
        for area, quantity, va, vb, tol in diff(old, new):
            print(f"{area} | {quantity}: {va} → {vb} (tolerance {tol})")
        sys.exit(0)
    if sys.argv[1:2] == ["--save"]:
        version, results = sys.argv[2], (sys.argv[3] if len(sys.argv) > 3 else "validation-results")
        target = ROOT / "docs" / "validation" / "history" / f"{version}.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps({"version": version, "rows": rows_of(results)}, indent=1) + "\n", "utf-8")
        print(target)
        sys.exit(0)
    results = sys.argv[1] if len(sys.argv) > 1 else "validation-results"
    target = Path(sys.argv[2] if len(sys.argv) > 2 else "docs/validation/report.md")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(build(results) + "\n", encoding="utf-8")
    print(target)
